def is_disposable_domain(domain: str) -> bool:
    """
    Sub-millisecond test against 600+ known disposable and burner domains.
    Handles subdomains (e.g. 'sub.mailinator.com' -> 'mailinator.com').
    """
    if not domain:
        return False
    clean_domain = domain.strip().lower().rstrip(".")
    if clean_domain in DISPOSABLE_DOMAINS:
        return True

    # Check root registrable domain fallback (e.g., xyz.mailinator.com)
    parts = clean_domain.split(".")
    if len(parts) > 2:
        parent_domain = ".".join(parts[-2:])
        if parent_domain in DISPOSABLE_DOMAINS:
            return True

    return False
